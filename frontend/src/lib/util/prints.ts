// Helpers for the prints page: reading a G-code file in the browser, and
// ranking the spools a print's filament may have come from.

import type { PrintSlot, Spool } from '../api/types.ts';

// The same lines as keep_line in backend/src/gcode.rs and static/rollcall-print.py.
const PREFIXES = ['; filament used', '; total filament', '; filament:', '; generated by'];

/** The comment lines Rollcall reads from G-code: a few kilobytes of a large file. */
export function gcodeSummary(text: string): string {
	const kept: string[] = [];
	let inBlock = false;
	for (const raw of text.split('\n')) {
		const line = raw.replace(/\r$/, '');
		if (line.startsWith('; HEADER_BLOCK_START') || line.startsWith('; CONFIG_BLOCK_START')) {
			inBlock = true;
		}
		if (inBlock || PREFIXES.some((p) => line.startsWith(p))) kept.push(line);
		if (line.startsWith('; HEADER_BLOCK_END') || line.startsWith('; CONFIG_BLOCK_END')) {
			inBlock = false;
		}
	}
	return kept.join('\n') + '\n';
}

function rgb(hex: string | null): [number, number, number] | null {
	const m = hex?.match(/^#?([0-9a-f]{6})/i);
	if (!m) return null;
	const n = parseInt(m[1], 16);
	return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** 0 for the same color, up to about 441 for black against white. */
export function colorDistance(a: string | null, b: string | null): number {
	const x = rgb(a);
	const y = rgb(b);
	if (!x || !y) return 500;
	return Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]);
}

const IN_USE = new Set(['active', 'drying', 'sealed']);

/**
 * The spools to offer for a slot, likeliest first: the preset's known
 * filament, then the same material, then the closest color. Empty and
 * archived spools, and spools shared with you to view only, are left out.
 */
export function spoolChoices(slot: PrintSlot, spools: Spool[]): Spool[] {
	const type = slot.filament_type?.toUpperCase() ?? null;
	const score = (s: Spool) =>
		(s.filament_id === slot.profile_filament_id ? 0 : 10_000) +
		(type && s.material_code.toUpperCase().startsWith(type) ? 0 : 1_000) +
		(s.status === 'sealed' ? 100 : 0) +
		colorDistance(slot.color_hex, s.color_hex) / 10;
	return spools
		.filter((s) => IN_USE.has(s.status) && s.access !== 'view')
		.sort((a, b) => score(a) - score(b));
}

/** "Bambu Lab PLA Basic · Jade White · #R-0001". */
export function spoolLabel(s: {
	brand_name: string;
	material_code: string;
	product_name: string | null;
	color_name: string;
	label_code: string | null;
}): string {
	return [
		`${s.brand_name} ${s.product_name ?? s.material_code}`,
		s.color_name,
		s.label_code ? `#${s.label_code}` : null
	]
		.filter(Boolean)
		.join(' · ');
}
