//! Reads what a print uses from the comments OrcaSlicer and Bambu Studio
//! write into their G-code: the grams per filament, and each filament's
//! preset name, type and color.
//!
//! - OrcaSlicer ends the file with `; filament used [g] = 1.23, 0, 4.56`, one
//!   value per filament slot (zeros for unused slots before the last used one).
//! - Bambu Studio's header has `; filament: 1,3` (the slots used) and
//!   `; total filament weight [g] : 1.23,4.56` (their grams, in that order).
//! - Both write their settings between `; CONFIG_BLOCK_START` and
//!   `; CONFIG_BLOCK_END`, including `filament_settings_id`, `filament_type`
//!   and `filament_colour`, separated by `;`.

use rust_decimal::Decimal;
use std::collections::HashMap;
use std::str::FromStr;

/// One filament slot that the print uses.
#[derive(Debug, Clone, PartialEq)]
pub struct SlotUsage {
    /// 1-based, as the slicer numbers its filaments.
    pub slot: i16,
    pub grams: Decimal,
    /// The slicer's filament preset (`filament_settings_id`).
    pub profile: Option<String>,
    pub filament_type: Option<String>,
    /// `#RRGGBB`.
    pub color_hex: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct SlicedPrint {
    /// "OrcaSlicer 2.3.1" or "BambuStudio 02.04.00.70".
    pub slicer: Option<String>,
    /// The slicer's printer preset (`printer_settings_id`).
    pub printer: Option<String>,
    pub slots: Vec<SlotUsage>,
}

/// Only the comment lines matter: the header, the config block and the
/// filament totals. Everything else can be dropped before uploading, which
/// keeps a 50 MB file down to a few kilobytes. `scripts/rollcall-print.py`
/// and the browser upload keep the same lines.
pub fn keep_line(line: &str, in_block: bool) -> bool {
    in_block
        || [
            "; filament used",
            "; total filament",
            "; filament:",
            "; generated by",
        ]
        .iter()
        .any(|p| line.starts_with(p))
}

pub fn parse(text: &str) -> SlicedPrint {
    let mut config: HashMap<String, String> = HashMap::new();
    let mut slicer = None;
    let mut used_g: Option<Vec<Decimal>> = None;
    let mut bambu_weights: Option<Vec<Decimal>> = None;
    let mut bambu_slots: Option<Vec<i16>> = None;
    let mut total: Option<Decimal> = None;

    for raw in text.lines() {
        let line = raw.trim_end_matches('\r');
        let Some(body) = line.strip_prefix(';') else {
            continue;
        };
        let body = body.trim();
        if let Some(rest) = body.strip_prefix("generated by ") {
            // "OrcaSlicer 2.3.1 on 2026-11-27 at 10:00:00 UTC"
            let name = rest.split(" on ").next().unwrap_or(rest).trim();
            slicer.get_or_insert_with(|| name.to_string());
        } else if slicer.is_none() && is_slicer_banner(body) {
            slicer = Some(body.to_string());
        } else if let Some(v) = body.strip_prefix("filament used [g] =") {
            used_g = Some(numbers(v));
        } else if let Some(v) = body.strip_prefix("total filament weight [g] :") {
            bambu_weights = Some(numbers(v));
        } else if let Some(v) = body.strip_prefix("filament:") {
            bambu_slots = Some(v.split(',').filter_map(|s| s.trim().parse().ok()).collect());
        } else if let Some(v) = body.strip_prefix("total filament used [g] =") {
            total = Decimal::from_str(v.trim()).ok();
        } else if let Some((k, v)) = body.split_once(" = ") {
            let k = k.trim();
            if k.chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            {
                config
                    .entry(k.to_string())
                    .or_insert_with(|| v.trim().to_string());
            }
        }
    }

    let list = |key: &str| config.get(key).map(|v| split_values(v)).unwrap_or_default();
    let profiles = list("filament_settings_id");
    let types = list("filament_type");
    let colors = list("filament_colour");

    // (slot, grams)
    let mut usage: Vec<(i16, Decimal)> = if let Some(g) = used_g {
        g.into_iter()
            .enumerate()
            .map(|(i, g)| (i as i16 + 1, g))
            .collect()
    } else if let (Some(w), Some(s)) = (&bambu_weights, &bambu_slots) {
        s.iter().copied().zip(w.iter().copied()).collect()
    } else if let Some(w) = bambu_weights.filter(|w| w.len() == 1) {
        vec![(1, w[0])]
    } else if let Some(t) = total.filter(|_| profiles.len() <= 1) {
        vec![(1, t)]
    } else {
        Vec::new()
    };
    usage.retain(|(slot, g)| *slot >= 1 && *g > Decimal::ZERO);

    let at = |v: &[String], slot: i16| {
        v.get(slot as usize - 1)
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
    };
    SlicedPrint {
        slicer,
        printer: config
            .get("printer_settings_id")
            .map(|v| unquote(v))
            .filter(|s| !s.is_empty()),
        slots: usage
            .into_iter()
            .map(|(slot, grams)| SlotUsage {
                slot,
                grams: grams.round_dp(2),
                profile: at(&profiles, slot),
                filament_type: at(&types, slot),
                color_hex: at(&colors, slot).and_then(|c| hex_color(&c)),
            })
            .collect(),
    }
}

fn is_slicer_banner(body: &str) -> bool {
    // Bambu Studio's first header line: "BambuStudio 02.04.00.70".
    let mut parts = body.split(' ');
    matches!(
        (parts.next(), parts.next(), parts.next()),
        (Some(name), Some(version), None)
            if ["BambuStudio", "OrcaSlicer", "PrusaSlicer", "SuperSlicer"].contains(&name)
                && version.chars().all(|c| c.is_ascii_digit() || c == '.')
    )
}

fn numbers(v: &str) -> Vec<Decimal> {
    v.split(',')
        .map(|s| Decimal::from_str(s.trim()).unwrap_or(Decimal::ZERO))
        .collect()
}

/// `"Bambu PLA Basic @BBL X1C";"Generic PETG"` or `PLA;PETG`: the slicers
/// join lists with `;` and quote items that need it, with C-style escapes.
pub fn split_values(v: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut chars = v.chars().peekable();
    let mut quoted = false;
    let mut started = false;
    while let Some(c) = chars.next() {
        match c {
            '"' if !started || quoted => {
                if quoted {
                    quoted = false;
                } else {
                    quoted = true;
                    started = true;
                }
            }
            '\\' if quoted => match chars.next() {
                Some('n') => cur.push('\n'),
                Some('r') => cur.push('\r'),
                Some('t') => cur.push('\t'),
                Some(other) => cur.push(other),
                None => {}
            },
            ';' if !quoted => {
                out.push(std::mem::take(&mut cur));
                started = false;
            }
            _ => {
                cur.push(c);
                started = true;
            }
        }
    }
    out.push(cur);
    out
}

fn unquote(v: &str) -> String {
    split_values(v).into_iter().next().unwrap_or_default()
}

/// `#RRGGBB` from `#rrggbb` or `#RRGGBBAA`.
fn hex_color(c: &str) -> Option<String> {
    let h = c.trim().trim_start_matches('#');
    (h.len() >= 6 && h[..6].chars().all(|c| c.is_ascii_hexdigit()))
        .then(|| format!("#{}", h[..6].to_ascii_uppercase()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dec(s: &str) -> Decimal {
        s.parse().unwrap()
    }

    const ORCA: &str = "\
; HEADER_BLOCK_START
; generated by OrcaSlicer 2.3.1 on 2026-11-27 at 10:00:00 UTC
; total layer number: 120
; filament: 1,3
; HEADER_BLOCK_END

G1 X10 Y10
;TYPE:Outer wall
; CONFIG_BLOCK_START
; filament_colour = #F4F4F0;#000000;#C12E1F
; filament_settings_id = \"Bambu Lab PLA Basic Jade White @X1C (Rollcall)\";\"Generic PETG @System\";\"Generic PLA @System\"
; filament_type = PLA;PETG;PLA
; printer_settings_id = \"Bambu Lab X1 Carbon 0.4 nozzle\"
; CONFIG_BLOCK_END

; filament used [mm] = 4100.12, 0.00, 380.50
; filament used [g] = 12.34, 0, 1.20
; total filament used [g] = 13.54
";

    const BAMBU: &str = "\
; HEADER_BLOCK_START
; BambuStudio 02.04.00.70
; model printing time: 1h 2m; total estimated time: 1h 9m
; total layer number: 120
; total filament length [mm] : 4100.12,380.50
; total filament volume [cm^3] : 9861.30,915.20
; total filament weight [g] : 12.34,1.20
; filament_density: 1.24,1.27,1.24
; filament: 1,3
; HEADER_BLOCK_END

; CONFIG_BLOCK_START
; filament_colour = #F4F4F0FF;#000000FF;#C12E1FFF
; filament_settings_id = \"Bambu PLA Basic @BBL X1C\";\"Generic PETG\";\"Bambu PLA Matte @BBL X1C\"
; filament_type = PLA;PETG;PLA
; printer_settings_id = Bambu Lab X1 Carbon 0.4 nozzle
; CONFIG_BLOCK_END
";

    #[test]
    fn orca_slots_by_position() {
        let p = parse(ORCA);
        assert_eq!(p.slicer.as_deref(), Some("OrcaSlicer 2.3.1"));
        assert_eq!(p.printer.as_deref(), Some("Bambu Lab X1 Carbon 0.4 nozzle"));
        assert_eq!(p.slots.len(), 2);
        assert_eq!(
            p.slots[0],
            SlotUsage {
                slot: 1,
                grams: dec("12.34"),
                profile: Some("Bambu Lab PLA Basic Jade White @X1C (Rollcall)".into()),
                filament_type: Some("PLA".into()),
                color_hex: Some("#F4F4F0".into()),
            }
        );
        assert_eq!(p.slots[1].slot, 3);
        assert_eq!(p.slots[1].profile.as_deref(), Some("Generic PLA @System"));
    }

    #[test]
    fn bambu_slots_from_the_used_list() {
        let p = parse(BAMBU);
        assert_eq!(p.slicer.as_deref(), Some("BambuStudio 02.04.00.70"));
        assert_eq!(p.printer.as_deref(), Some("Bambu Lab X1 Carbon 0.4 nozzle"));
        let s: Vec<_> = p.slots.iter().map(|s| (s.slot, s.grams)).collect();
        assert_eq!(s, vec![(1, dec("12.34")), (3, dec("1.20"))]);
        assert_eq!(
            p.slots[1].profile.as_deref(),
            Some("Bambu PLA Matte @BBL X1C")
        );
        assert_eq!(p.slots[1].color_hex.as_deref(), Some("#C12E1F"));
    }

    #[test]
    fn single_filament_total_and_windows_newlines() {
        let g = "; generated by OrcaSlicer 2.3.1 on x\r\n; filament_settings_id = \"Generic PLA\"\r\n; total filament used [g] = 7.5\r\n";
        let p = parse(g);
        assert_eq!(p.slots.len(), 1);
        assert_eq!(p.slots[0].grams, dec("7.5"));
        assert_eq!(p.slots[0].profile.as_deref(), Some("Generic PLA"));
    }

    #[test]
    fn nothing_to_find() {
        assert!(parse("G1 X0\nG1 X1\n").slots.is_empty());
        assert!(parse("; filament used [g] = 0, 0\n").slots.is_empty());
    }

    #[test]
    fn list_values() {
        assert_eq!(split_values("PLA;PETG"), vec!["PLA", "PETG"]);
        assert_eq!(
            split_values(r#""a;b";"say \"hi\"\n""#),
            vec!["a;b", "say \"hi\"\n"]
        );
        assert_eq!(split_values(""), vec![""]);
        assert_eq!(hex_color("#c12e1fff").as_deref(), Some("#C12E1F"));
        assert_eq!(hex_color("red"), None);
    }

    #[test]
    fn keeps_only_the_lines_that_matter() {
        assert!(keep_line("; filament used [g] = 1", false));
        assert!(keep_line("; filament: 1,3", false));
        assert!(!keep_line(";TYPE:Outer wall", false));
        assert!(!keep_line("G1 X1", false));
        assert!(keep_line("; anything", true));
    }
}
